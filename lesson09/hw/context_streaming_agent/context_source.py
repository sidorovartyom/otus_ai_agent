"""Источник контекста для агента.

Сейчас источник — локальный файл knowledge_base.md (небольшая база знаний
вымышленного облачного сервиса Otus Cloud). Функция get_context()
изолирует агента (agent.py) от способа получения контекста: чтобы
подключить вместо файла реальный API, достаточно поменять реализацию
этой функции (например, на httpx.get(...) к внутреннему сервису базы
знаний) - интерфейс для agent.py не изменится. См. README.md, раздел
"Как подключить контекст из API вместо файла".
"""

from __future__ import annotations

from pathlib import Path

_KB_PATH = Path(__file__).parent / "knowledge_base.md"


def get_context(topic: str | None = None) -> str:
    """Возвращает контекст, который нужно подставить агенту.

    Параметр topic зарезервирован под фильтрацию контекста по теме -
    сейчас база знаний достаточно мала, чтобы всегда отдавать её целиком.
    """
    return _KB_PATH.read_text(encoding="utf-8")
